pub fn encodedLen(bytes: []const u8) usize {
    var bits: usize = 0;
    for (bytes) |b| bits += lengths[b];
    return (bits + 7) / 8;
}

pub fn encode(w: *std.Io.Writer, bytes: []const u8) std.Io.Writer.Error!void {
    var acc: u64 = 0;
    var nbits: u8 = 0;
    for (bytes) |b| {
        const len = lengths[b];
        acc = (acc << @intCast(len)) | codes[b];
        nbits += len;
        while (nbits >= 8) {
            const shift: u6 = @intCast(nbits - 8);
            try w.writeByte(@truncate(acc >> shift));
            nbits -= 8;
            if (nbits == 0) acc = 0 else acc &= (@as(u64, 1) << @intCast(nbits)) - 1;
        }
    }
    if (nbits != 0) {
        const pad: u8 = 8 - nbits;
        const byte: u8 = @truncate((acc << @intCast(pad)) | ((@as(u64, 1) << @intCast(pad)) - 1));
        try w.writeByte(byte);
    }
}

pub fn decode(input: []const u8, out: []u8) error{ InvalidHuffman, OutputTooSmall }![]u8 {
    var node: usize = 0;
    var used: usize = 0;
    var trailing_bits: u8 = 0;
    var trailing_ones = true;
    for (input) |byte| {
        var bit_index: u4 = 0;
        while (bit_index < 8) : (bit_index += 1) {
            const shift: u3 = @intCast(7 - bit_index);
            const bit = (byte >> shift) & 1;
            const next_i = if (bit == 0) nodes[node].zero else nodes[node].one;
            if (next_i < 0) return error.InvalidHuffman;
            node = @intCast(next_i);
            trailing_bits += 1;
            trailing_ones = trailing_ones and bit == 1;
            const sym = nodes[node].symbol;
            if (sym >= 0) {
                if (sym == 256) return error.InvalidHuffman;
                if (used == out.len) return error.OutputTooSmall;
                out[used] = @intCast(sym);
                used += 1;
                node = 0;
                trailing_bits = 0;
                trailing_ones = true;
            }
        }
    }
    if (node != 0 and (trailing_bits > 7 or !trailing_ones)) return error.InvalidHuffman;
    return out[0..used];
}

